const { chromium } = require('playwright');
const { PNG } = require('pngjs');
const { execFileSync } = require('node:child_process');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '../..');
const php = process.env.PARKING_QA_PHP || 'C:/xampp/php/php.exe';
const fixtureScript = path.join(__dirname, 'parking-fixture.php');
const fixture = JSON.parse(execFileSync(php, [fixtureScript], { cwd: root, encoding: 'utf8' }));

(async () => {
    let browser;
    try {
        browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--use-angle=swiftshader', '--enable-webgl'] });
        const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
        await context.addCookies([{ name: fixture.cookie_name, value: fixture.cookie_value, url: 'http://127.0.0.1:8000', httpOnly: true, sameSite: 'Lax' }]);
        const page = await context.newPage();
        const errors = [];
        page.on('pageerror', (error) => errors.push(error.message));
        await page.goto(`http://127.0.0.1:8000/rentas?location=${fixture.location}`);
        await page.locator('.parking-tile').first().waitFor();
        await page.waitForFunction(() => document.querySelector('[data-parking-icon="settings"] svg'));
        assert.equal(await page.locator('.topbar #userMenuTrigger').isVisible(), true);
        assert.equal(await page.locator('#sidebar .nav-item.active').innerText(), 'Parqueo');
        await page.locator('.parking-space-option[data-space-code="QA-04"]').click();
        assert.match(await page.locator('#parking-selection').innerText(), /QA-04/);
        assert.match(await page.locator('[data-parking-submit]').innerText(), /QA-04/);
        await page.locator('.parking-space-option.available:not(.selected)').first().click();
        assert.match(await page.locator('#parking-selection').innerText(), /QA-03/);
        await page.locator('[data-parking-view="3d"]').click();
        await page.locator('.parking-canvas-stage canvas').waitFor();
        assert.equal(await page.locator('.parking-map-error').isVisible(), false);
        const canvas = page.locator('.parking-canvas-stage canvas');
        const before = await canvas.screenshot();
        const png = PNG.sync.read(before);
        const colors = new Set();
        for (let i = 0; i < png.data.length; i += 64) colors.add(`${png.data[i]},${png.data[i + 1]},${png.data[i + 2]}`);
        assert.ok(colors.size > 30, `Canvas blank or missing objects: ${colors.size} colors`);
        const bounds = await canvas.boundingBox();
        await page.mouse.move(bounds.x + bounds.width / 2, bounds.y + bounds.height / 2);
        await page.mouse.down();
        await page.mouse.move(bounds.x + bounds.width / 2 + 90, bounds.y + bounds.height / 2 + 20, { steps: 12 });
        await page.mouse.up();
        const after = await canvas.screenshot();
        assert.notDeepEqual(before, after, '3D view did not respond to interaction');
        await page.locator('[data-parking-reset]').click();
        await page.evaluate(() => window.scrollTo(0, 0));
        await page.screenshot({ path: path.join(root, 'storage/app/parking-qa-desktop.png'), fullPage: true });
        await page.locator('#userMenuTrigger').click();
        await page.locator('#themeToggle').click();
        await page.locator('#userMenuTrigger').click();
        assert.equal(await page.evaluate(() => document.documentElement.dataset.theme), 'light');
        await page.screenshot({ path: path.join(root, 'storage/app/parking-qa-light.png'), fullPage: true });
        await page.setViewportSize({ width: 390, height: 844 });
        await page.goto(`http://127.0.0.1:8000/rentas?location=${fixture.location}`);
        await page.locator('.parking-pc-required').waitFor({ state: 'visible' });
        assert.equal(await page.locator('#parking-entry-form').isVisible(), false);
        assert.equal(await page.locator('.parking-canvas-stage canvas').isVisible(), false);
        assert.equal(await page.locator('#userMenuTrigger').isVisible(), true, 'Mobile user menu missing');
        await page.screenshot({ path: path.join(root, 'storage/app/parking-qa-mobile.png'), fullPage: true });
        assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false, 'Mobile page overflows');
        await page.locator('#userMenuTrigger').click();
        await page.locator('#themeToggle').click();
        await page.locator('#userMenuTrigger').click();
        await page.waitForFunction(() => document.documentElement.dataset.theme === 'dark');
        await page.locator('#parkingPcTitle').click();
        await page.evaluate(() => window.scrollTo(0, 0));
        await page.screenshot({ path: path.join(root, 'storage/app/parking-qa-mobile-dark.png'), fullPage: true });
        const mobile = await browser.newContext({ userAgent: 'Mozilla/5.0 (iPhone; CPU iPhone OS 17_0 like Mac OS X) Mobile', viewport: { width: 1440, height: 1000 } });
        await mobile.addCookies(await context.cookies());
        const mobilePage = await mobile.newPage();
        for (const route of [`rentas?location=${fixture.location}`, 'rentas/configuracion']) {
            await mobilePage.goto(`http://127.0.0.1:8000/${route}`);
            await mobilePage.getByRole('heading', { name: 'Necesitas una computadora' }).waitFor();
            assert.equal(await mobilePage.locator('.parking-desktop-content').count(), 0);
            assert.equal(await mobilePage.locator('canvas').count(), 0);
        }
        await mobile.close();
        await page.setViewportSize({ width: 1440, height: 1000 });
        await page.locator('[data-parking-view="plan"]').click();
        await page.locator('.parking-space-option.occupied').first().click();
        await page.locator('[name="payment_confirmed"]').check();
        await page.locator('[data-parking-settle] button[type="submit"]').click();
        await page.locator('[data-settlement-dialog]').waitFor({ state: 'visible' });
        const modal = await page.locator('[data-settlement-dialog]').boundingBox();
        assert.ok(Math.abs(modal.x + modal.width / 2 - 720) < 3, 'Modal is not centered');
        await page.locator('[data-settlement-confirm]').click();
        await page.getByText('Liquidada · Espacio liberado').waitFor();
        await page.locator('#statusToast').waitFor({ state: 'visible' });
        await page.locator('#statusToast').waitFor({ state: 'detached' });
        assert.equal(errors.length, 0, errors.join('\n'));
        console.log(JSON.stringify({ passed: true, canvasColors: colors.size, screenshots: 4, responsive: true, interaction: true, settlement: true }));
    } finally {
        await browser?.close();
        execFileSync(php, [fixtureScript, 'cleanup', String(fixture.location), fixture.session_id], { cwd: root });
    }
})().catch((error) => { console.error(error); process.exitCode = 1; });
